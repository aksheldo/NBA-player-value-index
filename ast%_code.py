# 1. The URL found in your source code
url = "https://www.spotrac.com/nba/rankings/player/_/year/2025/sort/cap_total"
# 2. Set headers so Spotrac thinks we are a real browser
headers = {
   "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/91.0.4472.124 Safari/537.36"
}


# 3. Fetch the HTML
response = requests.get(url, headers=headers)


if response.status_code == 200:
   soup = BeautifulSoup(response.text, 'html.parser')


   # 4. Find the specific container list
   # Your source shows the data is inside <ul class="list-group mb-4 not-premium">
   # We select all list items (li) inside that list
   list_items = soup.select('ul.list-group li.list-group-item')


   data = []


   for item in list_items:
       try:
           # --- Extract Player Name ---
           # Look for the <a> tag with class 'link'
           player_tag = item.find('a', class_='link')
           if not player_tag:
               continue # Skip rows without a player (like banners)
           player_name = player_tag.get_text(strip=True)


           # --- Extract Rank ---
           # Look for the div with class 'fs-3' (font-size 3)
           rank_tag = item.find('div', class_='fs-3')
           rank = rank_tag.get_text(strip=True) if rank_tag else None
           salary_tag = item.find('span', class_='medium')
           salary = salary_tag.get_text(strip=True) if salary_tag else "0"
           info_tag = item.find('small')
           team = "N/A"
           position = "N/A"


           if info_tag:
               info_text = info_tag.get_text(strip=True)
               if "," in info_text:
                   parts = info_text.split(',')
                   team = parts[0].strip()
                   position = parts[1].strip()
               else:
                   team = info_text


           # Append to our data list
           data.append({
               "Rank": rank,
               "Player": player_name,
               "Team": team,
               "Position": position,
               "AAV Salary": salary
           })


       except Exception as e:
           # Skip any malformed rows silently
           continue


   # 5. Convert to Pandas DataFrame
   df = pd.DataFrame(data)


   # --- Data Cleaning ---
   # Convert Salary to a real number (remove '$' and ',')
   df['AAV Salary Value'] = df['AAV Salary'].astype(str).str.replace('$', '').str.replace(',', '')
   df['AAV Salary Value'] = pd.to_numeric(df['AAV Salary Value'], errors='coerce')


   # Display the first 10 rows
   print(f"Successfully scraped {len(df)} players.")
   display(df.head(510))


