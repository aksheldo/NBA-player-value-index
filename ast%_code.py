import unicodedata
import pandas as pd

# ---------- Helper: remove accents ----------
def remove_accents(name):
    return ''.join(
        c for c in unicodedata.normalize('NFD', str(name))
        if unicodedata.category(c) != 'Mn'
    )

# ---------- Clean BOTH datasets ----------
df['Player'] = df['Player'].apply(remove_accents)
df_ast['Player'] = df_ast['Player'].apply(remove_accents)

# Optional: remove suffixes (helps matching)
df['Player'] = df['Player'].str.replace(r'\b(Jr\.?|Sr\.?|III|II)\b', '', regex=True).str.strip()
df_ast['Player'] = df_ast['Player'].str.replace(r'\b(Jr\.?|Sr\.?|III|II)\b', '', regex=True).str.strip()

# ---------- Fix df_ast (keep 1 row per player, prefer 2TM) ----------
df_ast['is_2TM'] = df_ast['Team'] == '2TM'
df_ast = df_ast.sort_values(by='is_2TM', ascending=False)

df_ast = df_ast.drop_duplicates(subset='Player', keep='first')
df_ast = df_ast.drop(columns='is_2TM')

# ---------- Ensure df (salary) has no duplicates ----------
df = df.drop_duplicates(subset='Player')

# ---------- Get TOP 100 salaries ----------
df_top100 = df.sort_values('AAV Salary Value', ascending=False).head(100)

# ---------- Merge ----------
df_merged = pd.merge(df_top100, df_ast, on='Player', how='left')

# ---------- Final formatting ----------
df_merged = df_merged.sort_values('AAV Salary Value', ascending=False).reset_index(drop=True)

# ---------- Display ----------
print(f"Final dataset has {len(df_merged)} players.")
display(df_merged)

